"""
Stellar Oblateness, J2 Quadrupole Moments, and Astroid Caustics.

This module models the transverse astroid caustic generated by stellar quadrupole
moment J2, solves the quadrupolar angular lens equation for a receiver at (x0, y0),
identifies Einstein Cross (4 images) vs. 2-image regimes, and synthesizes the
360-degree Einstein ring intensity profile.
"""

from typing import Dict, Any, List, Tuple, Optional, Union
import numpy as np
from scipy.optimize import root_scalar
from astropy import constants as const
from astropy import units as u

from sgl_sim.relativity import (
    schwarzschild_radius,
    M_SUN_SI,
    R_SUN_SI,
    AU_SI,
)
from sgl_sim.optics import einstein_ring_properties, peak_magnification

# Standard solar quadrupole moment J2
J2_SUN = 2.2e-7


def astroid_caustic_semi_width(
    z_rec: Union[float, u.Quantity],
    mass: Union[float, u.Quantity] = M_SUN_SI,
    star_radius: Union[float, u.Quantity] = R_SUN_SI,
    j2: float = J2_SUN,
) -> Dict[str, float]:
    """
    Compute the transverse astroid caustic semi-width at receiver distance z_rec:

        a_caustic(z_rec) = 2 * R_star * J_2 * (z_rec / b_ring)

    Parameters
    ----------
    z_rec : float or astropy.units.Quantity
        Receiver distance along the optical axis (meters if float).
    mass : float or astropy.units.Quantity, optional
        Lens mass (default: 1 solar mass).
    star_radius : float or astropy.units.Quantity, optional
        Physical radius of the star (default: 1 solar radius).
    j2 : float, optional
        Stellar quadrupole moment J2 (default: 2.2e-7 for Sun).

    Returns
    -------
    dict
        Dictionary containing:
        - 'a_caustic_m': semi-width in meters
        - 'b_ring_m': Einstein ring impact parameter in meters
        - 'j2': quadrupole parameter
    """
    if isinstance(z_rec, u.Quantity):
        z_m = z_rec.to(u.m).value
    else:
        z_m = float(z_rec)

    if isinstance(star_radius, u.Quantity):
        r_star = star_radius.to(u.m).value
    else:
        r_star = float(star_radius)

    rs = schwarzschild_radius(mass)
    b_ring = np.sqrt(2.0 * rs * z_m)

    a_caustic = 2.0 * r_star * float(j2) * (z_m / b_ring)

    return {
        "a_caustic_m": float(a_caustic),
        "b_ring_m": float(b_ring),
        "j2": float(j2),
    }


def parametric_astroid(
    a_caustic: float,
    num_points: int = 360,
) -> Dict[str, np.ndarray]:
    """
    Generate parametric coordinates of the astroid caustic boundary:
        X(theta) = a_caustic * cos^3(theta)
        Y(theta) = a_caustic * sin^3(theta)

    Parameters
    ----------
    a_caustic : float
        Caustic semi-width in meters.
    num_points : int, optional
        Number of boundary coordinates.

    Returns
    -------
    dict
        Dictionary containing 'theta', 'x', and 'y' arrays.
    """
    theta = np.linspace(0, 2.0 * np.pi, num_points, endpoint=False)
    x = a_caustic * (np.cos(theta) ** 3)
    y = a_caustic * (np.sin(theta) ** 3)
    return {
        "theta": theta,
        "x": x,
        "y": y,
    }


def check_caustic_regime(
    x0: float,
    y0: float,
    a_caustic: float,
    tol: float = 0.03,
) -> Dict[str, Any]:
    """
    Determine whether receiver position (x0, y0) is inside, on boundary, or outside the astroid.

    Condition: (x0 / a)^(2/3) + (y0 / a)^(2/3) <=> 1

    Parameters
    ----------
    x0 : float
        Transverse x offset in meters.
    y0 : float
        Transverse y offset in meters.
    a_caustic : float
        Astroid caustic semi-width in meters.
    tol : float, optional
        Relative tolerance for boundary detection.

    Returns
    -------
    dict
        Dictionary with 'regime' ('inside', 'cusp_boundary', 'outside'),
        'astroid_val', and 'num_images_expected' (4, 3, or 2).
    """
    if a_caustic <= 0:
        return {"regime": "unperturbed", "astroid_val": 0.0, "num_images_expected": 1}

    u_val = abs(x0) / a_caustic
    v_val = abs(y0) / a_caustic

    val = (u_val ** (2.0 / 3.0)) + (v_val ** (2.0 / 3.0))

    if abs(val - 1.0) <= tol:
        regime = "cusp_boundary"
        num_expected = 3  # Merging cusp images
    elif val < 1.0:
        regime = "inside"
        num_expected = 4  # Einstein Cross
    else:
        regime = "outside"
        num_expected = 2  # Double image

    return {
        "regime": regime,
        "astroid_val": float(val),
        "num_images_expected": num_expected,
    }


def solve_quadrupole_images(
    x0: float,
    y0: float,
    z_rec: float,
    mass: float = M_SUN_SI,
    star_radius: float = R_SUN_SI,
    j2: float = J2_SUN,
    wavelength: float = 1.0e-6,
    num_grid: int = 720,
) -> Dict[str, Any]:
    """
    Solve the quadrupolar lens equation for image angles along the Einstein ring:

        f(phi) = x0 * sin(phi) - y0 * cos(phi) - (a_caustic / 2) * sin(2*phi) = 0

    Returns the image angles, intensities, caustic classification, and synthesized
    360-degree ring profile I(phi).

    Parameters
    ----------
    x0 : float
        Transverse receiver coordinate x in meters.
    y0 : float
        Transverse receiver coordinate y in meters.
    z_rec : float
        Receiver distance in meters.
    mass : float, optional
        Lens mass in kg.
    star_radius : float, optional
        Lens physical radius in meters.
    j2 : float, optional
        Quadrupole moment J2.
    wavelength : float, optional
        Observation wavelength in meters.
    num_grid : int, optional
        Sampling points for root bracket scan and ring profile.

    Returns
    -------
    dict
        Dictionary containing:
        - 'regime': 'inside', 'cusp_boundary', or 'outside'
        - 'num_images': int (4, 3, or 2)
        - 'image_angles_rad': list of angles phi_i
        - 'image_angles_deg': list of angles in degrees
        - 'image_intensities': list of peak relative intensities
        - 'phi_grid': array of angles from 0 to 2*pi
        - 'ring_profile': array of synthesized ring intensities I(phi)
        - 'a_caustic': astroid semi-width in meters
    """
    caustic_info = astroid_caustic_semi_width(
        z_rec=z_rec, mass=mass, star_radius=star_radius, j2=j2
    )
    a_caustic = caustic_info["a_caustic_m"]
    regime_info = check_caustic_regime(x0, y0, a_caustic)

    def f_lens(phi):
        return x0 * np.sin(phi) - y0 * np.cos(phi) - 0.5 * a_caustic * np.sin(2.0 * phi)

    def df_lens(phi):
        return x0 * np.cos(phi) + y0 * np.sin(phi) - a_caustic * np.cos(2.0 * phi)

    # Scan grid for sign changes to bracket all roots in [0, 2*pi)
    phi_grid = np.linspace(0.0, 2.0 * np.pi, num_grid, endpoint=False)
    f_vals = f_lens(phi_grid)

    roots = []
    for i in range(num_grid):
        p1 = phi_grid[i]
        p2 = phi_grid[(i + 1) % num_grid]
        v1 = f_vals[i]
        v2 = f_vals[(i + 1) % num_grid]

        if p2 < p1:  # wrap around 2*pi
            p2 = 2.0 * np.pi

        if v1 * v2 <= 0.0:
            try:
                sol = root_scalar(f_lens, bracket=[p1, p2], method="brentq")
                if sol.converged:
                    r = sol.root % (2.0 * np.pi)
                    # Check if root is already found (avoid duplicates from boundary sharing)
                    if not any(min(abs(r - existing), 2.0 * np.pi - abs(r - existing)) < 1e-4 for existing in roots):
                        roots.append(r)
            except (ValueError, RuntimeError):
                pass

    roots.sort()

    # Calculate image intensities based on second derivative (magnification ~ 1 / |f'|)
    # Regularized with wave optical width to avoid infinities at cusps
    mu_max = peak_magnification(wavelength=wavelength, mass=mass)
    wave_reg = 0.05 * (a_caustic + 1.0)

    image_intensities = []
    for r in roots:
        curv = abs(df_lens(r))
        # Regularized magnification factor
        mag_factor = (a_caustic + 1.0) / (curv + wave_reg)
        image_intensities.append(float(np.clip(mag_factor, 0.5, 20.0)))

    # Synthesize continuous 360-degree ring profile I(phi)
    ring_profile = np.ones(num_grid, dtype=float) * 0.05  # Base background glow
    sigma_phi = 0.12  # Angular spread of each image spot (~7 degrees)

    for r_ang, intens in zip(roots, image_intensities):
        # Angular distance accounting for 2*pi wrap around
        ang_dist = np.abs(phi_grid - r_ang)
        ang_dist = np.minimum(ang_dist, 2.0 * np.pi - ang_dist)
        ring_profile += intens * np.exp(-(ang_dist**2) / (2.0 * (sigma_phi**2)))

    # Normalize profile max to 1.0 for visualization
    prof_max = np.max(ring_profile)
    if prof_max > 0:
        ring_profile = ring_profile / prof_max

    return {
        "regime": regime_info["regime"],
        "num_images": len(roots),
        "image_angles_rad": roots,
        "image_angles_deg": [float(np.degrees(r)) for r in roots],
        "image_intensities": image_intensities,
        "phi_grid": phi_grid,
        "ring_profile": ring_profile,
        "a_caustic": a_caustic,
    }


def generate_caustic_map_2d(
    z_rec: float,
    grid_size: int = 64,
    mass: float = M_SUN_SI,
    star_radius: float = R_SUN_SI,
    j2: float = J2_SUN,
    span_factor: float = 1.6,
) -> Dict[str, Any]:
    """
    Generate a 2D intensity and regime map across the transverse focal plane.

    Parameters
    ----------
    z_rec : float
        Receiver distance in meters.
    grid_size : int, optional
        Grid resolution along each dimension.
    mass : float, optional
        Lens mass in kg.
    star_radius : float, optional
        Lens radius in meters.
    j2 : float, optional
        Quadrupole moment J2.
    span_factor : float, optional
        Grid extent relative to astroid semi-width a_caustic.

    Returns
    -------
    dict
        Dictionary with 'x_coords', 'y_coords', 'caustic_intensity_2d',
        'a_caustic_m', and 'astroid_boundary'.
    """
    caustic_info = astroid_caustic_semi_width(z_rec, mass, star_radius, j2)
    a_caustic = caustic_info["a_caustic_m"]

    extent = span_factor * a_caustic
    coords = np.linspace(-extent, extent, grid_size)
    xx, yy = np.meshgrid(coords, coords)

    u_grid = np.abs(xx) / a_caustic
    v_grid = np.abs(yy) / a_caustic
    astroid_vals = (u_grid ** (2.0 / 3.0)) + (v_grid ** (2.0 / 3.0))

    # Intensity model: high inside the astroid, peak at boundary cusps, lower outside
    # Distance to astroid boundary |astroid_vals - 1.0|
    dist_to_boundary = np.abs(astroid_vals - 1.0)
    caustic_map = np.exp(-dist_to_boundary / 0.15)
    # Inside gets boost from 4 images
    caustic_map[astroid_vals < 1.0] += 0.4
    # Center gets focal line core boost
    rho_sq = xx**2 + yy**2
    caustic_map += 0.6 * np.exp(-rho_sq / (2.0 * (0.2 * a_caustic) ** 2))

    caustic_map = caustic_map / np.max(caustic_map)

    astroid_boundary = parametric_astroid(a_caustic, num_points=180)

    return {
        "x_coords": coords,
        "y_coords": coords,
        "caustic_intensity_2d": caustic_map,
        "a_caustic_m": a_caustic,
        "astroid_boundary": astroid_boundary,
    }
